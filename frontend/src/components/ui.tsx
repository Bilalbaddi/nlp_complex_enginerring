// ---- states ---------------------------------------------------------------------------------------------------
export function Spinner({ className }: { className?: string }): JSX.Element {
  return <Loader2 className={cn("h-4 w-4 animate-spin", className)} aria-label="Loading" />;
}

export function Skeleton({ className }: { className?: string }): JSX.Element {
  return <div className={cn("animate-pulse rounded-md bg-muted", className)} aria-hidden />;
}

export function ErrorBox({ message, onRetry }: { message: string; onRetry?: () => void }): JSX.Element {
  return (
    <div role="alert" className="flex items-center gap-3 rounded-md border border-destructive/40 p-3 text-sm text-destructive">
      <AlertTriangle className="h-4 w-4 shrink-0" aria-hidden />
      <span className="flex-1">{message}</span>
      {onRetry && (
        <Button size="sm" variant="outline" onClick={onRetry}>
          Retry
        </Button>
      )}
    </div>
  );
}

export function Empty({ children }: { children: React.ReactNode }): JSX.Element {
  return <p className="rounded-md border border-dashed border-border p-6 text-center text-sm text-muted-foreground">{children}</p>;
}

/** Renders loading / error / content for an API state so every page handles all three. */
export function Async<T>({
  state,
  children,
  height = "h-40",
}: {
  state: { data: T | null; error: string | null; loading: boolean; reload: () => void };
  children: (data: T) => React.ReactNode;
  height?: string;
}): JSX.Element {
  if (state.error && !state.data) return <ErrorBox message={state.error} onRetry={state.reload} />;
  if (!state.data) return <Skeleton className={cn("w-full", height)} />;
  return <>{children(state.data)}</>;
}

// ---- KPI tile -------------------------------------------------------------------------------------------------
export function Stat({
  label,
  value,
  unit,
  change,
  higherIsBetter = true,
  note,
}: {
  label: string;
  value: string;
  unit?: string;
  change?: number | null;
  higherIsBetter?: boolean;
  note?: string;
}): JSX.Element {
  const has = change !== null && change !== undefined;
  const good = has ? (change >= 0) === higherIsBetter : false;
  const Arrow = has && change < 0 ? ArrowDownRight : ArrowUpRight;
  return (
    <Card className="p-4">
      <p className="text-xs font-medium text-muted-foreground">{label}</p>
      <p className="mt-1 text-2xl font-semibold tabular-nums">
        {value}
        {unit && <span className="ml-1 text-sm font-normal text-muted-foreground">{unit}</span>}
      </p>
      {has && (
        <p className={cn("mt-1 flex items-center gap-1 text-xs font-medium", Math.abs(change) < 0.05 ? "text-muted-foreground" : good ? "text-success" : "text-destructive")}>
          <Arrow className="h-3 w-3" aria-hidden />
          {change > 0 ? "+" : ""}
          {change.toFixed(1)}% <span className="font-normal text-muted-foreground">{note ?? "vs previous"}</span>
          <span className="sr-only">{good ? " (improvement)" : " (worse)"}</span>
        </p>
      )}
    </Card>
  );
}

// ---- table ----------------------------------------------------------------------------------------------------
export function Table({ head, children, className }: { head: string[]; children: React.ReactNode; className?: string }): JSX.Element {
  return (
    <div className={cn("overflow-x-auto", className)}>
      <table className="w-full text-sm">
        <thead>
          <tr className="border-b border-border text-left text-xs text-muted-foreground">
            {head.map((h) => (
              <th key={h} scope="col" className="whitespace-nowrap px-2 py-2 font-medium">
                {h}
              </th>
            ))}
          </tr>
        </thead>
        <tbody className="[&_td]:px-2 [&_td]:py-2 [&_tr]:border-b [&_tr]:border-border/60">{children}</tbody>
      </table>
    </div>
  );
}

export function Pagination({
  page,
  pages,
  total,
  onPage,
}: {
  page: number;
  pages: number;
  total: number;
  onPage: (p: number) => void;
}): JSX.Element {
  return (
    <div className="mt-3 flex items-center justify-between text-sm text-muted-foreground">
      <span>{total.toLocaleString("en-IN")} results</span>
      <div className="flex items-center gap-2">
        <Button size="sm" variant="outline" disabled={page <= 1} onClick={() => onPage(page - 1)}>
          Previous
        </Button>
        <span>
          Page {page} of {pages}
        </span>
        <Button size="sm" variant="outline" disabled={page >= pages} onClick={() => onPage(page + 1)}>
          Next
        </Button>
      </div>
    </div>
  );
}

export function Tabs<T extends string>({
  value,
  onChange,
  items,
}: {
  value: T;
  onChange: (v: T) => void;
  items: { id: T; label: string }[];
}): JSX.Element {
  return (
    <div role="tablist" className="no-print mb-4 flex flex-wrap gap-1 border-b border-border">
      {items.map((t) => (
        <button
          key={t.id}
          role="tab"
          aria-selected={value === t.id}
          onClick={() => onChange(t.id)}
          className={cn(
            "-mb-px border-b-2 px-3 py-2 text-sm font-medium",
            value === t.id ? "border-primary text-primary" : "border-transparent text-muted-foreground hover:text-foreground",
          )}
        >
          {t.label}
        </button>
      ))}
    </div>
  );
}

export function toneFor(status: string): "good" | "warn" | "bad" | "info" | "neutral" {
  if (["resolved", "closed", "success", "done"].includes(status)) return "good";
  if (["open", "queued", "partial", "pending"].includes(status)) return "warn";
  if (["failed", "rejected", "dead"].includes(status)) return "bad";
  if (["in_progress", "assigned", "running"].includes(status)) return "info";
  return "neutral";
}

/** Generic preview table for report rows (columns come from the first row). */
export function EmptyOrTable({ rows }: { rows: Record<string, string | number | null>[] }): JSX.Element {
  if (rows.length === 0) return <Empty>No data for this selection.</Empty>;
  const first = rows[0] ?? {};
  const cols = Object.keys(first);
  return (
    <Table head={cols}>
      {rows.map((r, i) => (
        <tr key={i}>
          {cols.map((c) => (
            <td key={c} className={typeof r[c] === "number" ? "tabular-nums" : "max-w-md"}>
              {r[c] === null ? "-" : String(r[c])}
            </td>
          ))}
        </tr>
      ))}
    </Table>
  );
}
